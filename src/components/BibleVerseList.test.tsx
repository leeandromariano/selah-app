import { fireEvent, render, screen, waitFor } from '@testing-library/react'
import { describe, expect, it, vi } from 'vitest'
import { BibleVerseList } from './BibleVerseList'
import type { AnnotationStore } from '../bible/annotations'
vi.mock('../bible/favoritesFeature', () => ({ bibleFavoritesEnabled: true }))

const location = { translation: 'ntlh', book: 'esdras', chapter: 1 }
const verses = [{ number: 9, endNumber: 10, text: 'Versículo fictício.' }]
const makeStore = () => ({ list: vi.fn().mockResolvedValue([]), save: vi.fn().mockResolvedValue(undefined), remove: vi.fn().mockResolvedValue(undefined), listFavorites: vi.fn().mockResolvedValue([]), listAllFavorites: vi.fn().mockResolvedValue([]), addFavorite: vi.fn().mockResolvedValue(undefined), removeFavorite: vi.fn().mockResolvedValue(undefined) })

describe('destaques e anotações na Bíblia', () => {
  it('salva cor e anotação para a conta e o intervalo correto', async () => {
    const store = makeStore()
    render(<BibleVerseList userId="user-fictional" location={location} verses={verses} copyright="Atribuição fictícia" store={store as AnnotationStore} highlighted={() => false} />)
    await waitFor(() => expect(store.list).toHaveBeenCalled())
    fireEvent.click(screen.getByRole('button', { name: 'Versículo 9–10' }))
    fireEvent.click(screen.getByRole('button', { name: 'Destacar em azul-claro' }))
    await screen.findByText('Salvo na sua conta.')
    fireEvent.click(screen.getByRole('button', { name: 'Anotar' }))
    fireEvent.change(screen.getByLabelText('Anotação'), { target: { value: 'Minha nota fictícia' } })
    fireEvent.click(screen.getByRole('button', { name: 'Salvar anotação' }))
    await waitFor(() => expect(store.save).toHaveBeenLastCalledWith({ user_id: 'user-fictional', translation: 'ntlh', book: 'esdras', chapter: 1, verse_start: 9, verse_end: 10, color: 'blue', note: 'Minha nota fictícia' }))
    expect(document.getElementById('bible-verse-9')).toHaveClass('bible-mark-blue')
  })
  it('copia o versículo com referência e atribuição sem gravá-lo na conta', async () => {
    const store = makeStore(), writeText = vi.fn().mockResolvedValue(undefined)
    Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText } })
    render(<BibleVerseList userId="user-fictional" location={location} verses={verses} copyright="Atribuição fictícia" store={store as AnnotationStore} highlighted={() => false} />)
    await waitFor(() => expect(store.list).toHaveBeenCalled())
    fireEvent.click(screen.getByRole('button', { name: 'Versículo 9–10' }))
    fireEvent.click(screen.getByRole('button', { name: 'Copiar' }))
    await screen.findByText('Texto copiado.')
    expect(writeText).toHaveBeenCalledWith('Versículo fictício.\nEsdras 1:9-10 (NTLH)\nAtribuição fictícia\nAcesse o app: http://localhost:3000/#biblia/ntlh/esdras/1/9')
    expect(store.save).not.toHaveBeenCalled()
  })
  it('não informa sucesso quando a gravação é recusada', async () => {
    const store = makeStore(); store.save.mockRejectedValue(Error('denied'))
    render(<BibleVerseList userId="user-fictional" location={location} verses={verses} copyright="Atribuição fictícia" store={store as AnnotationStore} highlighted={() => false} />)
    await waitFor(() => expect(store.list).toHaveBeenCalled())
    fireEvent.click(screen.getByRole('button', { name: 'Versículo 9–10' }))
    fireEvent.click(screen.getByRole('button', { name: 'Destacar em rosa' }))
    expect(await screen.findByText('Não foi possível salvar. Tente novamente.')).toBeVisible()
    expect(document.getElementById('bible-verse-9')).not.toHaveClass('bible-mark-pink')
  })
  it('preserva a anotação ao remover somente a cor e exclui o registro quando ambos ficam vazios', async () => {
    const saved = { user_id: 'user-fictional', translation: 'ntlh', book: 'esdras', chapter: 1, verse_start: 9, verse_end: 10, color: 'pink' as const, note: 'Minha nota' }
    const store = makeStore(); store.list.mockResolvedValue([saved])
    render(<BibleVerseList userId="user-fictional" location={location} verses={verses} copyright="Atribuição fictícia" store={store as AnnotationStore} highlighted={() => false} />)
    const action = await screen.findByRole('button', { name: 'Versículo 9–10, com anotação' })
    expect(document.getElementById('bible-verse-9')).toHaveClass('bible-mark-pink')
    fireEvent.click(action)
    fireEvent.click(screen.getByRole('button', { name: 'Anotar' }))
    expect(screen.getByLabelText('Anotação')).toHaveValue('Minha nota')
    fireEvent.click(screen.getByRole('button', { name: 'Remover destaque' }))
    await screen.findByText('Salvo na sua conta.')
    expect(store.save).toHaveBeenCalledWith({ ...saved, color: null })
    fireEvent.change(screen.getByLabelText('Anotação'), { target: { value: '' } })
    fireEvent.click(screen.getByRole('button', { name: 'Salvar anotação' }))
    await waitFor(() => expect(store.remove).toHaveBeenCalled())
    expect(screen.queryByRole('button', { name: 'Versículo 9–10, com anotação' })).not.toBeInTheDocument()
  })
  it('favorita e desfavorita sem alterar destaque ou anotação', async () => {
    const store = makeStore()
    render(<BibleVerseList userId="user-fictional" location={location} verses={verses} copyright="Atribuição fictícia" store={store as AnnotationStore} highlighted={() => false} />)
    await waitFor(() => expect(store.listFavorites).toHaveBeenCalled())
    fireEvent.click(screen.getByRole('button', { name: 'Versículo 9–10' }))
    await waitFor(() => expect(screen.getByRole('button', { name: 'Favoritar' })).toBeEnabled())
    fireEvent.click(screen.getByRole('button', { name: 'Favoritar' }))
    await screen.findByRole('button', { name: 'Favoritado' })
    expect(store.addFavorite).toHaveBeenCalledWith({ user_id: 'user-fictional', translation: 'ntlh', book: 'esdras', chapter: 1, verse_start: 9, verse_end: 10 })
    fireEvent.click(screen.getByRole('button', { name: 'Favoritado' }))
    await waitFor(() => expect(store.removeFavorite).toHaveBeenCalled())
    expect(store.save).not.toHaveBeenCalled()
  })
  it('aplica ações a versículos avulsos sem sobrescrever as notas existentes', async () => {
    const store = makeStore()
    store.list.mockResolvedValue([{ user_id: 'user-fictional', translation: 'ntlh', book: 'esdras', chapter: 1, verse_start: 9, verse_end: 10, color: 'pink', note: 'Nota preservada' }])
    const writeText = vi.fn().mockResolvedValue(undefined)
    Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText } })
    render(<BibleVerseList userId="user-fictional" location={location} verses={[...verses, { number: 12, text: 'Outro texto fictício.' }]} copyright="Atribuição fictícia" store={store as AnnotationStore} highlighted={() => false} />)
    await screen.findByRole('button', { name: 'Versículo 9–10, com anotação' })
    fireEvent.click(screen.getByRole('button', { name: 'Versículo 9–10, com anotação' }))
    fireEvent.click(screen.getByRole('button', { name: 'Versículo 12' }))
    expect(screen.getByRole('group', { name: 'Ações dos versículos selecionados' })).toBeVisible()
    fireEvent.click(screen.getByRole('button', { name: 'Destacar selecionados em azul-claro' }))
    await screen.findByText('Salvo na sua conta.')
    expect(store.save).toHaveBeenCalledWith(expect.objectContaining({ verse_start: 9, note: 'Nota preservada', color: 'blue' }))
    expect(store.save).toHaveBeenCalledWith(expect.objectContaining({ verse_start: 12, color: 'blue' }))
    fireEvent.click(screen.getByRole('button', { name: 'Favoritar' }))
    await screen.findByText('Adicionados aos favoritos.')
    expect(store.addFavorite).toHaveBeenCalledTimes(2)
    fireEvent.click(screen.getByRole('button', { name: 'Copiar' }))
    await screen.findByText('Texto copiado.')
    expect(writeText).toHaveBeenCalledWith(expect.stringContaining('Acesse o app: http://localhost:3000/#biblia/ntlh/esdras/1'))
  })
})
