import { act, fireEvent, render, screen } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { afterEach, describe, expect, it, vi } from 'vitest'
import { ConsistencySection } from './ConsistencySection'
import { supabase } from '../lib/supabase'
import { consistencyFixture } from '../test/consistencyBoundary'
import type { Consistency } from '../consistency/repository'

const pending = consistencyFixture({ status: 'pending_today', current_streak: 3, best_streak: 5, total_days: 8, total_devotionals: 10, last_completed_day: '2026-10-27', first_month: '2018-12-01' })
function respond(value: Consistency) {
  vi.mocked(supabase.rpc).mockImplementation((_name, args) => ({ abortSignal: async () => ({ data: consistencyFixture({ ...value, month: (args as { p_month?: string })?.p_month ?? value.current_month, days: undefined }), error: null }) }) as never)
}
afterEach(() => { vi.useRealTimers(); vi.restoreAllMocks() })
describe('seção pessoal de constância', () => {
  it('acumula eventos no mesmo render sem ultrapassar os limites do servidor', async () => {
    respond(pending)
    render(<ConsistencySection userId="batched-fiction" />)
    await screen.findByRole('table')
    act(() => {
      screen.getByRole('button', { name: 'Mês anterior' }).click()
      screen.getByRole('button', { name: 'Mês anterior' }).click()
    })
    await screen.findByRole('table', { name: 'agosto de 2026' })
    act(() => {
      for (let i = 0; i < 5; i++) screen.getByRole('button', { name: 'Próximo mês' }).click()
    })
    expect(await screen.findByRole('table', { name: 'outubro de 2026' })).toBeVisible()
    expect(screen.getByRole('button', { name: 'Próximo mês' })).toBeDisabled()
  })
  it('acumula cliques com resposta pendente e conserva mês após foco', async () => {
    respond(pending)
    render(<ConsistencySection userId="rapid-fiction" />)
    await screen.findByRole('table')
    let finish!: (value: unknown) => void
    vi.mocked(supabase.rpc).mockReturnValueOnce({ abortSignal: () => new Promise(resolve => { finish = resolve }) } as never)
    fireEvent.click(screen.getByRole('button', { name: 'Mês anterior' }))
    fireEvent.click(screen.getByRole('button', { name: 'Mês anterior' }))
    await screen.findByRole('table', { name: 'agosto de 2026' })
    await act(async () => { finish({ data: consistencyFixture({ ...pending, month: '2026-09-01' }), error: null }) })
    fireEvent(window, new Event('focus'))
    fireEvent(document, new Event('visibilitychange'))
    expect(await screen.findByRole('table', { name: 'agosto de 2026' })).toBeVisible()
  })
  it('mostra estado inicial somente após consulta válida e distingue aberturas', async () => {
    render(<ConsistencySection userId="fiction" />)
    expect(await screen.findByText(/Seu primeiro dia começa/)).toBeVisible()
    expect(screen.getByText('Ofensiva atual').parentElement).toHaveTextContent('0 dias consecutivos')
    expect(screen.getByText(/não mede sua fé nem seu valor pessoal/)).toBeVisible()
    expect(screen.getByRole('button', { name: 'Mês anterior' })).toBeDisabled()
  })
  it('ontem mantém ofensiva pendente e recorde histórico separado', async () => {
    respond(pending)
    render(<ConsistencySection userId="fiction" />)
    expect(await screen.findByText(/Ainda pode manter sua sequência/)).toBeVisible()
    expect(screen.getByText('Ofensiva atual').parentElement).toHaveTextContent('3 dias consecutivos')
    expect(screen.getByText('Recorde pessoal').parentElement).toHaveTextContent('5 dias')
    expect(screen.getByText('Devocionais concluídos').parentElement).toHaveTextContent('10')
    expect(screen.getByText('Hoje: pendente')).toBeVisible()
  })
  it('dia cumprido é acessível por texto, marcador e aria-current, além de cores', async () => {
    const value = consistencyFixture({ status: 'completed_today', current_streak: 1, best_streak: 1, total_days: 1, total_devotionals: 1, today_completed: true, last_completed_day: '2026-10-28' })
    vi.mocked(supabase.rpc).mockReturnValue({ abortSignal: async () => ({ data: value, error: null }) } as never)
    render(<ConsistencySection userId="fiction" />)
    expect(await screen.findByText(/Conclusão de hoje registrada/)).toBeVisible()
    const day = screen.getByLabelText('28 de outubro de 2026, hoje: 1 devocional concluído')
    expect(day).toHaveAttribute('aria-current', 'date')
    expect(day.parentElement).toHaveTextContent('✓')
    expect(screen.getByRole('table', { name: 'outubro de 2026' })).toBeVisible()
    expect(screen.getByLabelText('29 de outubro de 2026: data futura')).toBeVisible()
  })
  it('interrupção incentiva retomada sem zerar recorde ou culpar o leitor', async () => {
    respond({ ...pending, status: 'interrupted', current_streak: 0, last_completed_day: '2026-10-26' })
    render(<ConsistencySection userId="fiction" />)
    expect(await screen.findByText(/Você pode recomeçar hoje/)).toBeVisible()
    expect(screen.getByText('Recorde pessoal').parentElement).toHaveTextContent('5 dias')
    expect(screen.getByText('Ofensiva atual').parentElement).toHaveTextContent('0 dias consecutivos')
  })
  it('navega meses por teclado sem alterar contadores nem enviar data de conclusão', async () => {
    respond(pending)
    const user = userEvent.setup()
    render(<ConsistencySection userId="fiction" />)
    await screen.findByRole('table')
    const previous = screen.getByRole('button', { name: 'Mês anterior' })
    previous.focus(); await user.keyboard('{Enter}')
    expect(await screen.findByRole('table', { name: 'setembro de 2026' })).toBeVisible()
    expect(previous).toHaveFocus()
    expect(screen.getByText('Ofensiva atual').parentElement).toHaveTextContent('3 dias consecutivos')
    await user.click(screen.getByRole('button', { name: 'Mês atual' }))
    expect(await screen.findByRole('table', { name: 'outubro de 2026' })).toBeVisible()
    expect(screen.getByRole('button', { name: 'Próximo mês' })).toBeDisabled()
    expect(vi.mocked(supabase.rpc).mock.calls.every(([name, args]) => name === 'get_my_consistency' && Object.keys(args ?? {}).join(',') === 'p_month')).toBe(true)
  })
  it('erro de rede não é mostrado como histórico vazio e permite nova tentativa', async () => {
    vi.mocked(supabase.rpc).mockReturnValueOnce({ abortSignal: async () => { throw Error('private@example.invalid') } } as never)
    const user = userEvent.setup()
    render(<ConsistencySection userId="fiction" />)
    expect(await screen.findByRole('alert')).toHaveTextContent('Verifique sua conexão')
    expect(screen.getByRole('alert')).not.toHaveTextContent('private@')
    expect(screen.queryByText(/Seu primeiro dia começa/)).not.toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: 'Tentar carregar consistência' }))
    expect(await screen.findByText(/Seu primeiro dia começa/)).toBeVisible()
  })
  it('atualização de fundo não desabilita navegação por teclado nem sobrescreve mês mais novo', async () => {
    respond(pending)
    const user = userEvent.setup()
    render(<ConsistencySection userId="fiction" />)
    await user.click(await screen.findByRole('button', { name: 'Mês anterior' }))
    await screen.findByRole('table', { name: 'setembro de 2026' })
    let finish!: (value: unknown) => void
    vi.mocked(supabase.rpc).mockReturnValueOnce({ abortSignal: () => new Promise(resolve => { finish = resolve }) } as never)
    const next = screen.getByRole('button', { name: 'Próximo mês' })
    next.focus(); fireEvent(window, new Event('focus'))
    await act(async () => { await Promise.resolve() })
    expect(next).toBeEnabled()
    await user.keyboard('{Enter}')
    await screen.findByRole('table', { name: 'outubro de 2026' })
    await act(async () => { finish({ data: consistencyFixture({ ...pending, month: '2026-09-01' }), error: null }) })
    expect(screen.getByRole('table', { name: 'outubro de 2026' })).toBeVisible()
  })
  it('não exibe resposta atrasada de uma conta depois da troca de usuário', async () => {
    let finish!: (value: unknown) => void
    vi.mocked(supabase.rpc).mockReturnValueOnce({ abortSignal: () => new Promise(resolve => { finish = resolve }) } as never)
    const { rerender } = render(<ConsistencySection userId="first-fiction" />)
    rerender(<ConsistencySection userId="second-fiction" />)
    await screen.findByText(/Seu primeiro dia começa/)
    await act(async () => { finish({ data: pending, error: null }) })
    expect(screen.queryByText(/Ainda pode manter sua sequência/)).not.toBeInTheDocument()
    expect(screen.getByText('Ofensiva atual').parentElement).toHaveTextContent('0 dias consecutivos')
  })
  it('consulta após virada do dia usa hoje do servidor mesmo com relógio local adulterado', async () => {
    vi.useFakeTimers(); vi.setSystemTime(new Date('2099-01-01T00:00:00Z'))
    const today = consistencyFixture({ ...pending, status: 'completed_today', current_streak: 3, today_completed: true, last_completed_day: '2026-10-28' })
    const tomorrow = consistencyFixture({ ...pending, server_now: '2026-10-29T03:00:00Z', server_today: '2026-10-29', last_completed_day: '2026-10-28' })
    vi.mocked(supabase.rpc).mockReturnValueOnce({ abortSignal: async () => ({ data: today, error: null }) } as never).mockReturnValueOnce({ abortSignal: async () => ({ data: tomorrow, error: null }) } as never)
    render(<ConsistencySection userId="fiction" />)
    await act(async () => { await Promise.resolve() })
    expect(screen.getByText('Hoje: concluído ✓')).toBeVisible()
    await act(async () => { await vi.advanceTimersByTimeAsync(60000) })
    expect(screen.getByText('Hoje: pendente')).toBeVisible()
    expect(screen.getByText(/Referência do servidor: 29 de outubro de 2026/)).toBeVisible()
    expect(vi.mocked(supabase.rpc)).toHaveBeenCalledTimes(2)
  })
  it('nova conclusão solicita atualização e falha de fundo identifica dados anteriores', async () => {
    respond(pending)
    const { rerender } = render(<ConsistencySection userId="fiction" refreshKey={0} />)
    await screen.findByText(/Ainda pode manter/)
    vi.mocked(supabase.rpc).mockReturnValueOnce({ abortSignal: async () => ({ data: null, error: { code: '42501', message: 'private account' } }) } as never)
    rerender(<ConsistencySection userId="fiction" refreshKey={1} />)
    expect(await screen.findByRole('alert')).toHaveTextContent('última consulta ao servidor')
    expect(screen.getByRole('alert')).not.toHaveTextContent('private account')
    expect(screen.getByText('Ofensiva atual').parentElement).toHaveTextContent('3 dias consecutivos')
    fireEvent(window, new Event('focus'))
    await screen.findByText(/Ainda pode manter/)
  })
})
